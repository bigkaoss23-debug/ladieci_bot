-- FUNCTION: supersede_closeout_attempt
CREATE OR REPLACE FUNCTION public.supersede_closeout_attempt(p_closeout_correlation_id uuid, p_actor text, p_reason text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_row public.service_closeout_attempts%ROWTYPE;
BEGIN
  IF p_closeout_correlation_id IS NULL THEN
    RETURN jsonb_build_object('ok',false,'code','INVALID_ARGUMENTS');
  END IF;
  IF p_actor IS NULL OR btrim(p_actor) = '' THEN
    RETURN jsonb_build_object('ok',false,'code','INVALID_ACTOR');
  END IF;

  SELECT * INTO v_row FROM public.service_closeout_attempts
   WHERE closeout_correlation_id = p_closeout_correlation_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok',false,'code','ATTEMPT_NOT_FOUND');
  END IF;

  IF v_row.status = 'completed' THEN
    RETURN jsonb_build_object('ok',false,'code','CANNOT_SUPERSEDE_COMPLETED_ATTEMPT');
  END IF;
  IF v_row.status = 'superseded' THEN
    RETURN jsonb_build_object('ok',true,'code','ALREADY_SUPERSEDED','idempotent',true,'attempt',to_jsonb(v_row));
  END IF;

  UPDATE public.service_closeout_attempts
     SET status = 'superseded', superseded_at = now(), supersession_reason = p_reason, updated_at = now()
   WHERE closeout_correlation_id = p_closeout_correlation_id
  RETURNING * INTO v_row;

  UPDATE public.service_incidents
     SET resolution_status = 'superseded',
         resolution_type   = 'closeout_attempt_superseded',
         resolved_by       = p_actor,
         resolved_at       = now(),
         updated_at        = now()
   WHERE closeout_correlation_id = p_closeout_correlation_id
     AND resolution_status IN ('pending','acknowledged');

  RETURN jsonb_build_object('ok',true,'code','SUPERSEDED','idempotent',false,'attempt',to_jsonb(v_row));
END;
$function$
;

-- FUNCTION: mesa_prepare_table_order_v1
CREATE OR REPLACE FUNCTION public.mesa_prepare_table_order_v1()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_session public.table_sessions%ROWTYPE;
  v_table public.restaurant_tables%ROWTYPE;
  v_item jsonb;
  v_items jsonb := '[]'::jsonb;
  v_source_line_id uuid;
  v_raw_id text;
  v_covers_total integer;
BEGIN
  IF NEW.table_session_id IS NULL THEN RETURN NEW; END IF;

  SELECT * INTO v_session FROM public.table_sessions
   WHERE id = NEW.table_session_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'MESA_SESSION_NOT_FOUND' USING ERRCODE='P0002'; END IF;
  IF v_session.status <> 'open' THEN RAISE EXCEPTION 'MESA_SESSION_NOT_OPEN' USING ERRCODE='55000'; END IF;

  -- First comanda on a walk-in Mesa: require and lock in the real covers count.
  -- Any later comanda already has v_session.covers_total set, so this is a no-op
  -- and a stray table_covers_total_input value on that request is simply ignored.
  v_covers_total := v_session.covers_total;
  IF v_covers_total IS NULL THEN
    IF NEW.table_covers_total_input IS NULL
       OR NEW.table_covers_total_input NOT BETWEEN 1 AND 99
    THEN RAISE EXCEPTION 'MESA_COVERS_REQUIRED' USING ERRCODE='22023'; END IF;
    v_covers_total := NEW.table_covers_total_input;
  END IF;
  NEW.table_covers_total_input := NULL;

  SELECT * INTO v_table FROM public.restaurant_tables
   WHERE id = v_session.table_id FOR SHARE;
  IF NOT FOUND OR v_table.active IS NOT TRUE THEN
    RAISE EXCEPTION 'MESA_TABLE_UNAVAILABLE' USING ERRCODE='55000';
  END IF;

  IF jsonb_typeof(NEW.items) <> 'array' OR jsonb_array_length(NEW.items) = 0 THEN
    RAISE EXCEPTION 'MESA_ITEMS_REQUIRED' USING ERRCODE='22023';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(NEW.items)
  LOOP
    v_raw_id := v_item ->> 'lineId';
    BEGIN
      v_source_line_id := CASE WHEN v_raw_id IS NULL THEN gen_random_uuid() ELSE v_raw_id::uuid END;
    EXCEPTION WHEN invalid_text_representation THEN
      RAISE EXCEPTION 'MESA_LINE_ID_INVALID' USING ERRCODE='22023';
    END;
    v_items := v_items || jsonb_build_array(
      jsonb_set(v_item, '{lineId}', to_jsonb(v_source_line_id::text), true)
    );
  END LOOP;

  NEW.items := v_items;
  -- SLICE 3.1 FIX -- removed: NEW.service_session_id := v_session.service_session_id;
  -- ordenes_assign_service_session (fires next, alphabetically) is now the
  -- SOLE writer of ordenes.service_session_id for every order, Mesa or not --
  -- see PART 1 header above for the full rationale.
  NEW.table_number_snapshot := v_table.table_number;
  NEW.table_name_snapshot := v_table.display_name;
  NEW.table_command_number := v_session.next_command_number;
  NEW.canal := 'BANCO';
  NEW.tipo_consegna := 'RITIRO';
  NEW.delivery_fee := 0;

  UPDATE public.table_sessions
     SET covers_total = v_covers_total,
         next_command_number = next_command_number + 1,
         updated_at = now()
   WHERE id = v_session.id;

  RETURN NEW;
END
$function$
;

-- FUNCTION: mesa_snapshot_order_lines_v1
CREATE OR REPLACE FUNCTION public.mesa_snapshot_order_lines_v1()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_session public.table_sessions%ROWTYPE;
  v_item jsonb;
  v_line_index integer;
  v_quantity integer;
  v_unit_index integer;
  v_total_units integer := 0;
  v_seen_units integer := 0;
  v_source_line_id uuid;
  v_description text;
  v_unit_gross_cents bigint;
  v_total_gross_cents bigint := 0;
  v_gross_remaining_cents bigint;
  v_net_total_cents bigint;
  v_net_remaining_cents bigint;
  v_unit_net_cents bigint;
BEGIN
  IF NEW.table_session_id IS NULL THEN RETURN NEW; END IF;

  SELECT * INTO v_session FROM public.table_sessions WHERE id = NEW.table_session_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'MESA_SESSION_NOT_FOUND' USING ERRCODE='P0002'; END IF;

  FOR v_item, v_line_index IN
    SELECT value, ordinality::integer FROM jsonb_array_elements(NEW.items) WITH ORDINALITY
  LOOP
    v_quantity := COALESCE((v_item ->> 'quantity')::integer, (v_item ->> 'q')::integer, 1);
    v_unit_gross_cents := round(COALESCE(
      (v_item ->> 'finalUnitPrice')::numeric,
      (v_item ->> 'p')::numeric
    ) * 100)::bigint;
    IF v_quantity < 1 OR v_unit_gross_cents < 0 THEN
      RAISE EXCEPTION 'MESA_ITEM_SNAPSHOT_INVALID' USING ERRCODE='22023';
    END IF;
    v_total_units := v_total_units + v_quantity;
    v_total_gross_cents := v_total_gross_cents + (v_quantity * v_unit_gross_cents);
  END LOOP;

  v_net_total_cents := round(COALESCE(NEW.totale, 0) * 100)::bigint;
  IF v_total_units < 1 OR v_total_gross_cents <= 0 OR v_net_total_cents < 0
     OR v_net_total_cents > v_total_gross_cents THEN
    RAISE EXCEPTION 'MESA_ORDER_TOTAL_INVALID' USING ERRCODE='22023';
  END IF;
  v_net_remaining_cents := v_net_total_cents;
  v_gross_remaining_cents := v_total_gross_cents;

  FOR v_item, v_line_index IN
    SELECT value, ordinality::integer FROM jsonb_array_elements(NEW.items) WITH ORDINALITY
  LOOP
    v_quantity := COALESCE((v_item ->> 'quantity')::integer, (v_item ->> 'q')::integer, 1);
    v_source_line_id := (v_item ->> 'lineId')::uuid;
    v_description := left(COALESCE(NULLIF(v_item ->> 'fantasyName',''), NULLIF(v_item ->> 'n',''), NULLIF(v_item ->> 'classicName',''), 'Producto'), 240);
    v_unit_gross_cents := round(COALESCE(
      (v_item ->> 'finalUnitPrice')::numeric,
      (v_item ->> 'p')::numeric
    ) * 100)::bigint;

    FOR v_unit_index IN 1..v_quantity
    LOOP
      v_seen_units := v_seen_units + 1;
      IF v_seen_units = v_total_units THEN
        v_unit_net_cents := v_net_remaining_cents;
      ELSE
        v_unit_net_cents := floor(
          (v_net_remaining_cents::numeric * v_unit_gross_cents::numeric) / v_gross_remaining_cents::numeric
        )::bigint;
      END IF;
      v_net_remaining_cents := v_net_remaining_cents - v_unit_net_cents;
      v_gross_remaining_cents := v_gross_remaining_cents - v_unit_gross_cents;

      INSERT INTO public.table_order_lines(
        workspace_id, table_session_id, service_session_id, order_id,
        source_line_id, source_line_index, unit_index, description,
        product_snapshot, gross_amount, discount_amount, net_amount
      ) VALUES (
        v_session.workspace_id, v_session.id, NEW.service_session_id, NEW.id,
        v_source_line_id, v_line_index, v_unit_index, v_description,
        v_item, v_unit_gross_cents / 100.0,
        (v_unit_gross_cents - v_unit_net_cents) / 100.0,
        v_unit_net_cents / 100.0
      );
    END LOOP;
  END LOOP;

  RETURN NEW;
END
$function$
;

-- FUNCTION: order_entity_anchor_v1
CREATE OR REPLACE FUNCTION public.order_entity_anchor_v1()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
DECLARE
  v_workspace       uuid;
  v_business_day    uuid;
  v_epoch           integer;
  v_ticket_number   integer;
  v_uid             uuid;
BEGIN
  IF NEW.service_session_id IS NULL THEN
    RAISE EXCEPTION 'ORDER_WITHOUT_SERVICE_SESSION' USING ERRCODE='P0001';
  END IF;
  IF NEW.order_uid IS NOT NULL THEN
    RAISE EXCEPTION 'ORDER_UID_FORGERY' USING ERRCODE='P0001';
  END IF;

  SELECT business_day_id INTO v_business_day
    FROM public.service_sessions WHERE id = NEW.service_session_id;
  IF v_business_day IS NULL THEN
    RAISE EXCEPTION 'SERVICE_PERIOD_WITHOUT_BUSINESS_DAY' USING ERRCODE='P0001';
  END IF;

  IF NEW.table_session_id IS NOT NULL THEN
    SELECT ts.workspace_id INTO v_workspace
      FROM public.table_sessions ts WHERE ts.id = NEW.table_session_id;
    IF v_workspace IS NULL THEN
      RAISE EXCEPTION 'MESA_SESSION_NOT_FOUND' USING ERRCODE='P0002';
    END IF;
  ELSE
    v_workspace := public.mesa_singleton_workspace_v1();
  END IF;

  UPDATE public.business_days
     SET next_ticket_number = next_ticket_number + 1, updated_at = now()
   WHERE id = v_business_day
  RETURNING next_ticket_number - 1, ticket_epoch INTO v_ticket_number, v_epoch;

  INSERT INTO public.order_entities
    (workspace_id, display_order_id, service_session_id, table_session_id,
     business_day_id, ticket_epoch, ticket_number, created_at)
  VALUES
    (v_workspace, NEW.id, NEW.service_session_id, NEW.table_session_id,
     v_business_day, v_epoch, v_ticket_number, COALESCE(NEW.created_at, now()))
  RETURNING order_uid INTO v_uid;

  NEW.order_uid := v_uid;
  RETURN NEW;
END $function$
;

