function catalogFromSnapshot(dir) {
  const functions = readJson(dir, 'functions.json');
  const raw = readJson(dir, 'structure.json');
  const ex = readJson(dir, 'extras_staging_readonly_query_2026-09-27.json').extras;
  const ex2 = readJson(dir, 'extras2_staging_readonly_query_2026-09-27.json');
  if (!/replident":"d for all 62/.test(JSON.stringify(ex2.result_summary)) || ex2.result_summary.tables_checked !== raw.tables.length) throw new Error('extras2 does not cover every table');
  const structure = {
    schemas: raw.schemas,
    tables: raw.tables.map((t) => ({ ...t, replident: 'd', persistence: 'p', reloptions: null })),
    sequences: raw.sequences,
    publications: (raw.publications || []).filter((p) => SCHEMAS.includes(p.schema)),
  };
  const extras = {
    function_comments: ex.function_comments,
    schema_comments: (ex.schema_comments || []).filter((s) => s.schema !== 'public'),
    platform_triggers: ex.app_triggers_on_platform_tables.map((t) => ({ table: t.table, name: t.name, def: t.def, enabled: t.enabled })),
  };
  return { functions, structure, extras };
}

// A CHECK written with BETWEEN is stored as a nested AND ((e >= lo) AND (e <= hi)) that the parser never flattens into the enclosing AND
// list, while re-parsing its deparsed text does flatten it. Writing that exact shape back as BETWEEN restores the original expression tree,
// so pg_get_constraintdef round-trips byte for byte (proved by the catalog comparison, not assumed).
const betweenForm = (def) => def.replace(/\(\(([^()]*(?:\([^()]*\))?[^()]*) >= ([^()\s]+)\) AND \(\1 <= ([^()\s]+)\)\)/g, '($1 BETWEEN $2 AND $3)');

