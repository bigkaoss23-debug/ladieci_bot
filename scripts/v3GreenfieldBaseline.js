// parse "grantee=privs/grantor" -> {grantee, privs: [{p, grant}]}
function parseAcl(item) {
  const m = /^([^=]*)=([^/]*)\/(.*)$/.exec(item);
  if (!m) throw new Error('unparsable aclitem ' + item);
  const grantee = m[1] === '' ? 'PUBLIC' : m[1].replace(/^"|"$/g, '');
  const privs = []; const s = m[2];
  for (let i = 0; i < s.length; i += 1) { const grant = s[i + 1] === '*'; privs.push({ p: s[i], grant }); if (grant) i += 1; }
  return { grantee, privs, grantor: m[3] };
}
function grantsSql(kind, objSql, acl, owner, map) {
  // Start from a clean slate for every role the platform's default privileges may have touched, then grant exactly the catalog ACL.
  const out = [`REVOKE ALL ON ${kind} ${objSql} FROM PUBLIC, ${API_ROLES.join(', ')};`];
  for (const it of acl || []) {
    const a = parseAcl(it);
    if (a.grantee === owner) continue;
    const plain = a.privs.filter((x) => !x.grant).map((x) => map[x.p]);
    const withGrant = a.privs.filter((x) => x.grant).map((x) => map[x.p]);
    const role = a.grantee === 'PUBLIC' ? 'PUBLIC' : qi(a.grantee);
    if (plain.length) out.push(`GRANT ${plain.join(', ')} ON ${kind} ${objSql} TO ${role};`);
    if (withGrant.length) out.push(`GRANT ${withGrant.join(', ')} ON ${kind} ${objSql} TO ${role} WITH GRANT OPTION;`);
  }
  return out;
}
